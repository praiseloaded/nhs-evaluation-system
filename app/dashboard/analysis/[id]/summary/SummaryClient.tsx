// ─── Colours (shared palette) ─────────────────────────────────────────────────
const C = {
  navy:    '#1e3a5f',
  blue:    '#1e40af',
  lblue:   '#dbeafe',
  green:   '#15803d',
  lgreen:  '#dcfce7',
  amber:   '#b45309',
  lamber:  '#fef9c3',
  red:     '#991b1b',
  lred:    '#fee2e2',
  lgray:   '#f3f4f6',
  mgray:   '#e5e7eb',
  dgray:   '#374151',
  black:   '#111827',
  white:   '#ffffff',
  accblue: '#3b82f6',
  litblue: '#93c5fd',
}

type Doc = any

function hex(h: string): [number, number, number] {
  const n = parseInt(h.replace('#', ''), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

const PW = 210
const PH = 297
const ML = 15
const MR = 15
const CW = PW - ML - MR
const HEADER_H = 18
const FOOTER_H = 12

// ─── Header & footer ──────────────────────────────────────────────────────────
function drawHeader(doc: Doc, jobTitle: string, createdAt: string) {
  doc.setFillColor(...hex(C.navy))
  doc.rect(0, 0, PW, HEADER_H, 'F')
  doc.setFillColor(...hex(C.accblue))
  doc.rect(0, HEADER_H - 1, PW, 1, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.setTextColor(...hex(C.white))
  doc.text('NHS JobReady AI', ML, 8)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  doc.setTextColor(...hex(C.litblue))
  doc.text('Application Summary Report', ML, 13)

  const title = jobTitle.length > 52 ? jobTitle.slice(0, 52) + '…' : jobTitle
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(8.5)
  doc.setTextColor(...hex(C.white))
  doc.text(title, PW - MR, 8, { align: 'right' })
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  doc.setTextColor(...hex(C.litblue))
  doc.text(createdAt, PW - MR, 13, { align: 'right' })
}

function drawFooter(doc: Doc, pageNum: number, totalPages: number, createdAt: string) {
  const y = PH - FOOTER_H
  doc.setFillColor(...hex(C.lgray))
  doc.rect(0, y, PW, FOOTER_H, 'F')
  doc.setFillColor(...hex(C.mgray))
  doc.rect(0, y, PW, 0.3, 'F')
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(6.5)
  doc.setTextColor(...hex(C.dgray))
  doc.text('Confidential — for applicant use only. Generated by NHS JobReady AI.', ML, y + 4.5)
  doc.text(createdAt, PW / 2, y + 4.5, { align: 'center' })
  doc.setFont('helvetica', 'bold')
  doc.text(`Page ${pageNum} of ${totalPages}`, PW - MR, y + 4.5, { align: 'right' })
}

// ─── Cursor ───────────────────────────────────────────────────────────────────
class Cursor {
  y: number
  doc: Doc
  jobTitle: string
  createdAt: string
  pageNum: number

  constructor(doc: Doc, jobTitle: string, createdAt: string) {
    this.doc = doc; this.jobTitle = jobTitle; this.createdAt = createdAt
    this.y = HEADER_H + 8; this.pageNum = 1
  }

  check(needed: number) {
    if (this.y + needed > PH - FOOTER_H - 4) this.newPage()
  }

  newPage() {
    this.doc.addPage(); this.pageNum++
    drawHeader(this.doc, this.jobTitle, this.createdAt)
    this.y = HEADER_H + 8
  }

  gap(n = 4) { this.y += n }
}

// ─── Drawing helpers ──────────────────────────────────────────────────────────
function sectionHeading(cur: Cursor, title: string) {
  cur.check(14); cur.gap(4)
  cur.doc.setFillColor(...hex(C.lblue))
  cur.doc.rect(ML, cur.y, CW, 9, 'F')
  cur.doc.setFont('helvetica', 'bold')
  cur.doc.setFontSize(9)
  cur.doc.setTextColor(...hex(C.blue))
  cur.doc.text(title.toUpperCase(), ML + 4, cur.y + 6)
  cur.y += 12
}

function scoreBar(cur: Cursor, label: string, value: number) {
  cur.check(10)
  const pct   = Math.max(0, Math.min(100, Math.round(value || 0)))
  const color = pct >= 70 ? C.green : pct >= 50 ? C.amber : C.red
  const barW  = CW - 100 - 12

  cur.doc.setFont('helvetica', 'normal')
  cur.doc.setFontSize(8)
  cur.doc.setTextColor(...hex(C.dgray))
  cur.doc.text(label, ML, cur.y + 3)

  cur.doc.setFillColor(...hex(C.mgray))
  cur.doc.roundedRect(ML + 100, cur.y, barW, 4, 1, 1, 'F')
  if (pct > 0) {
    cur.doc.setFillColor(...hex(color))
    cur.doc.roundedRect(ML + 100, cur.y, barW * pct / 100, 4, 1, 1, 'F')
  }
  cur.doc.setFont('helvetica', 'bold')
  cur.doc.setFontSize(8)
  cur.doc.setTextColor(...hex(color))
  cur.doc.text(`${pct}%`, ML + 100 + barW + 4, cur.y + 3)
  cur.y += 8
}

function metricCards(cur: Cursor, cards: Array<{ label: string; value: string | number; bg: string; fg: string }>) {
  const cardW = (CW - (cards.length - 1) * 3) / cards.length
  cur.check(22)
  cards.forEach((card, i) => {
    const x = ML + i * (cardW + 3)
    cur.doc.setFillColor(...hex(card.bg))
    cur.doc.roundedRect(x, cur.y, cardW, 18, 2, 2, 'F')
    cur.doc.setFont('helvetica', 'bold')
    cur.doc.setFontSize(18)
    cur.doc.setTextColor(...hex(card.fg))
    cur.doc.text(String(card.value), x + cardW / 2, cur.y + 11, { align: 'center' })
    cur.doc.setFont('helvetica', 'normal')
    cur.doc.setFontSize(7)
    cur.doc.text(card.label, x + cardW / 2, cur.y + 16, { align: 'center' })
  })
  cur.y += 22
}

interface BoxSegment {
  text: string
  size?: number
  bold?: boolean
  italic?: boolean
  color?: string
  indent?: number
}

function boxSegments(cur: Cursor, segments: BoxSegment[], bg: string) {
  const PAD_X = 5; const PAD_Y = 5; const LINE_GAP = 1.2
  type RL = { text: string; size: number; bold: boolean; italic: boolean; color: string; indent: number; leading: number }
  const rendLines: RL[] = []

  for (const seg of segments) {
    const size = seg.size ?? 8.5; const bold = seg.bold ?? false
    const italic = seg.italic ?? false; const color = seg.color ?? C.dgray
    const indent = seg.indent ?? 0; const leading = size * 0.45 + LINE_GAP
    cur.doc.setFont('helvetica', italic ? 'oblique' : bold ? 'bold' : 'normal')
    cur.doc.setFontSize(size)
    const wrapped: string[] = cur.doc.splitTextToSize(seg.text || '', CW - PAD_X * 2 - indent)
    for (const w of wrapped) rendLines.push({ text: w, size, bold, italic, color, indent, leading })
  }

  const totalH = rendLines.reduce((acc, l) => acc + l.leading, 0) + PAD_Y * 2
  cur.check(totalH + 3)
  cur.doc.setFillColor(...hex(bg))
  cur.doc.roundedRect(ML, cur.y, CW, totalH, 2, 2, 'F')
  let ty = cur.y + PAD_Y + (rendLines[0]?.leading ?? 5) * 0.75
  for (const l of rendLines) {
    cur.doc.setFont('helvetica', l.italic ? 'oblique' : l.bold ? 'bold' : 'normal')
    cur.doc.setFontSize(l.size)
    cur.doc.setTextColor(...hex(l.color))
    cur.doc.text(l.text, ML + PAD_X + l.indent, ty)
    ty += l.leading
  }
  cur.y += totalH + 3
}

function pillRow(cur: Cursor, items: Array<{ label: string; bg: string; fg: string }>) {
  cur.check(10)
  let px = ML; const rowH = 6
  for (const item of items) {
    const w = cur.doc.getStringUnitWidth(item.label) * 7.5 / cur.doc.internal.scaleFactor + 8
    if (px + w > ML + CW) { cur.y += rowH; px = ML }
    cur.doc.setFillColor(...hex(item.bg))
    cur.doc.roundedRect(px, cur.y - 3.5, w, 5.5, 1.5, 1.5, 'F')
    cur.doc.setFont('helvetica', 'normal')
    cur.doc.setFontSize(7.5)
    cur.doc.setTextColor(...hex(item.fg))
    cur.doc.text(item.label, px + 3, cur.y + 0.5)
    px += w + 3
  }
  cur.y += rowH + 2
}

// ─── Build summary PDF ────────────────────────────────────────────────────────
async function buildSummaryPDF(
  analysis: Props['analysis'],
  result: any,
  jobTitle: string,
  createdAt: string,
  isPro: boolean,
): Promise<Blob> {
  const { jsPDF } = await import('jspdf')
  await import('jspdf-autotable')

  const doc: Doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' })
  const sb  = result.scoredBreakdown ?? {}
  const am  = result.atsMatch ?? {}
  const sc  = result.statementScan ?? {}
  const overall = sb.overallScore ?? 0
  const overallColor = overall >= 70 ? C.green : overall >= 50 ? C.amber : C.red

  drawHeader(doc, jobTitle, createdAt)
  const cur = new Cursor(doc, jobTitle, createdAt)

  // ── Cover block ────────────────────────────────────────────────────────────
  doc.setFillColor(...hex(C.navy))
  doc.roundedRect(ML, cur.y, CW, 48, 4, 4, 'F')

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  doc.setTextColor(...hex(C.litblue))
  doc.text('NHS JOBREADY AI  ·  APPLICATION SUMMARY REPORT', ML + 6, cur.y + 8)

  const titleLines = doc.splitTextToSize(jobTitle, CW - 100)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(15)
  doc.setTextColor(...hex(C.white))
  titleLines.forEach((l: string, i: number) => doc.text(l, ML + 6, cur.y + 16 + i * 7))

  const meta = [analysis.band, analysis.location, createdAt].filter(Boolean).join('  ·  ')
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.setTextColor(...hex(C.litblue))
  doc.text(meta, ML + 6, cur.y + 30)

  // Overall score right
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(40)
  doc.setTextColor(...hex(overallColor))
  doc.text(`${overall}%`, PW - MR - 6, cur.y + 26, { align: 'right' })
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  doc.setTextColor(...hex(C.litblue))
  doc.text('OVERALL SCORE', PW - MR - 6, cur.y + 32, { align: 'right' })

  // Free tier notice
  if (!isPro) {
    doc.setFont('helvetica', 'italic')
    doc.setFontSize(7)
    doc.setTextColor(...hex(C.litblue))
    doc.text('Summary view — upgrade to Pro for the full report', ML + 6, cur.y + 40)
  }

  cur.y += 55

  // ── Score breakdown ────────────────────────────────────────────────────────
  sectionHeading(cur, 'Score Overview')
  ;[
    ['Overall Score',     sb.overallScore],
    ['Criteria Coverage', sb.criteriaCoverage],
    ['Values Alignment',  sb.valuesAlignment],
  ].forEach(([l, v]) => scoreBar(cur, String(l), Number(v || 0)))
  cur.gap(4)

  // ── Statement scan ─────────────────────────────────────────────────────────
  if (sc.wordCount != null) {
    sectionHeading(cur, 'Statement Overview')
    metricCards(cur, [
      { label: 'Word count',    value: sc.wordCount ?? 0,     bg: C.lblue,  fg: C.blue  },
      { label: 'Has examples',  value: sc.hasExamples ? 'Yes' : 'No',  bg: sc.hasExamples ? C.lgreen : C.lred, fg: sc.hasExamples ? C.green : C.red },
      { label: 'Results shown', value: sc.resultsPresent ? 'Yes' : 'No', bg: sc.resultsPresent ? C.lgreen : C.lred, fg: sc.resultsPresent ? C.green : C.red },
    ])
    cur.gap(4)
  }

  // ── ATS match ──────────────────────────────────────────────────────────────
  if (am.totalKeywords) {
    sectionHeading(cur, 'ATS Keyword Match')
    metricCards(cur, [
      { label: 'Found',   value: am.foundCount   ?? 0, bg: C.lgreen, fg: C.green },
      { label: 'Missing', value: am.missingCount  ?? 0, bg: C.lred,   fg: C.red   },
      { label: 'Total',   value: am.totalKeywords ?? 0, bg: C.lblue,  fg: C.blue  },
    ])
    if (am.keywordsFound?.length) {
      cur.doc.setFont('helvetica', 'bold')
      cur.doc.setFontSize(8)
      cur.doc.setTextColor(...hex(C.dgray))
      cur.doc.text('Keywords found:', ML, cur.y); cur.y += 5
      pillRow(cur, am.keywordsFound.map((k: string) => ({ label: k, bg: C.lgreen, fg: C.green })))
    }
    cur.gap(4)
  }

  // ── NHS Values ─────────────────────────────────────────────────────────────
  const nhsVals = result.nhsValues ?? []
  if (nhsVals.length) {
    sectionHeading(cur, 'NHS Values Demonstrated')
    pillRow(cur, nhsVals.map((v: any) => ({
      label: `${v.classification === 'absent' ? '✗' : '✓'}  ${v.name}`,
      bg: v.classification === 'absent' ? C.lred : C.lgreen,
      fg: v.classification === 'absent' ? C.red  : C.green,
    })))
    cur.gap(4)
  }

  // ── Strengths (claims only — free tier) ────────────────────────────────────
  const strengths = result.strengths ?? []
  if (strengths.length) {
    sectionHeading(cur, 'Key Strengths')
    strengths.forEach((s: any) => {
      const claim = typeof s === 'string' ? s : s.claim ?? ''
      boxSegments(cur, [
        { text: `✓  ${claim}`, size: 8.5, bold: true, color: C.green },
      ], C.lgreen)
    })
    cur.gap(2)
  }

  // ── Pro upsell (free users only) ───────────────────────────────────────────
  if (!isPro) {
    cur.check(60)
    cur.gap(6)

    // Purple gradient box
    doc.setFillColor(...hex('#4c1d95'))
    doc.roundedRect(ML, cur.y, CW, 52, 4, 4, 'F')

    doc.setFont('helvetica', 'bold')
    doc.setFontSize(13)
    doc.setTextColor(...hex(C.white))
    doc.text('Want the full report?', ML + 8, cur.y + 12)

    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8.5)
    doc.setTextColor(...hex('#c4b5fd'))
    const bodyLines = doc.splitTextToSize(
      'Upgrade to Pro to unlock every criteria assessment, all recommendations with targeted fix actions, rejection risk analysis, band coaching, operational realism scoring, language mirroring detail — all in a professional PDF.',
      CW - 16
    )
    let by = cur.y + 20
    bodyLines.forEach((l: string) => { doc.text(l, ML + 8, by); by += 4.5 })

    const features = ['Full criteria & evidence breakdown', 'Targeted recommendations per gap', 'Rejection risk gate analysis', 'Band coaching & panel tips']
    features.forEach((f, i) => {
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(8)
      doc.setTextColor(...hex('#86efac'))
      doc.text('✓', ML + 8, by + i * 4.5)
      doc.setTextColor(...hex(C.white))
      doc.text(f, ML + 14, by + i * 4.5)
    })

    cur.y += 58
  }

  // ── Footer on all pages ────────────────────────────────────────────────────
  const totalPages = doc.internal.getNumberOfPages()
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p)
    drawFooter(doc, p, totalPages, createdAt)
  }

  return doc.output('blob')
}

// ─── Component ────────────────────────────────────────────────────────────────
export function SummaryClient({ analysis, result, isPro }: Props) {
  const router   = useRouter()
  const [status, setStatus]   = useState<'idle' | 'loading' | 'done' | 'error'>('idle')
  const [errorMsg, setErrorMsg] = useState('')

  const jobTitle  = analysis.jobTitle
  const createdAt = new Date(analysis.createdAt).toLocaleDateString('en-GB', {
    day: 'numeric', month: 'long', year: 'numeric',
  })

  async function handleDownload() {
    setStatus('loading')
    setErrorMsg('')
    try {
      const blob = await buildSummaryPDF(analysis, result, jobTitle, createdAt, isPro)
      const url  = URL.createObjectURL(blob)
      const a    = document.createElement('a')
      a.href     = url
      a.download = `NHS-JobReady-${jobTitle.replace(/[^a-zA-Z0-9]/g, '-').slice(0, 40)}-Summary.pdf`
      a.click()
      URL.revokeObjectURL(url)
      setStatus('done')
    } catch (err: any) {
      setErrorMsg(err.message ?? 'Download failed')
      setStatus('error')
    }
  }

  return (
    <div style={{ minHeight: '100vh', backgroundColor: '#f9fafb', fontFamily: 'system-ui, sans-serif', display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', padding: '2rem' }}>
      <div style={{ backgroundColor: '#fff', border: '1px solid #e5e7eb', borderRadius: 16, padding: '48px 40px', maxWidth: 480, width: '100%', textAlign: 'center' }}>

        <div style={{ width: 64, height: 64, borderRadius: '50%', backgroundColor: '#dbeafe', display: 'flex', alignItems: 'center', justifyContent: 'center', margin: '0 auto 20px' }}>
          <FileText size={28} color="#1e40af" />
        </div>

        <h1 style={{ fontSize: 20, fontWeight: 800, color: '#111827', marginBottom: 8 }}>
          {isPro ? 'Application Summary' : 'Free Summary Report'}
        </h1>
        <p style={{ fontSize: 14, color: '#6b7280', marginBottom: 6, lineHeight: 1.6 }}>{jobTitle}</p>
        <p style={{ fontSize: 12, color: '#9ca3af', marginBottom: isPro ? 28 : 16 }}>
          {isPro
            ? 'A4 PDF — overall score, ATS match, NHS values, key strengths, and statement overview.'
            : 'Includes overall score, ATS keywords, NHS values, and key strengths. Upgrade for the full report.'}
        </p>

        {!isPro && (
          <button
            onClick={() => router.push('/upgrade')}
            style={{ width: '100%', marginBottom: 10, padding: '11px 16px', backgroundColor: '#4c1d95', color: '#fff', border: 'none', borderRadius: 10, fontSize: 14, fontWeight: 700, cursor: 'pointer', display: 'inline-flex', alignItems: 'center', justifyContent: 'center', gap: 8, fontFamily: 'inherit' }}
          >
            <Lock size={15} /> Upgrade for Full Report
          </button>
        )}

        {status === 'idle' && (
          <button
            onClick={handleDownload}
            style={{ width: '100%', padding: '14px', backgroundColor: '#1e40af', color: '#fff', border: 'none', borderRadius: 10, fontSize: 15, fontWeight: 700, cursor: 'pointer', display: 'inline-flex', alignItems: 'center', justifyContent: 'center', gap: 8, fontFamily: 'inherit' }}
          >
            <Download size={18} /> Download Summary PDF
          </button>
        )}

        {status === 'loading' && (
          <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 12 }}>
            <Loader2 size={36} color="#1e40af" style={{ animation: 'spin 1s linear infinite' }} />
            <p style={{ fontSize: 14, color: '#6b7280' }}>Building your summary…</p>
          </div>
        )}

        {status === 'done' && (
          <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 12 }}>
            <CheckCircle2 size={40} color="#15803d" />
            <p style={{ fontSize: 14, color: '#15803d', fontWeight: 600 }}>Downloaded successfully!</p>
            <button onClick={handleDownload} style={{ padding: '10px 20px', backgroundColor: '#f3f4f6', color: '#374151', border: '1px solid #e5e7eb', borderRadius: 8, fontSize: 13, cursor: 'pointer', fontFamily: 'inherit' }}>
              Download again
            </button>
          </div>
        )}

        {status === 'error' && (
          <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 12 }}>
            <p style={{ fontSize: 13, color: '#991b1b', backgroundColor: '#fee2e2', padding: '10px 16px', borderRadius: 8 }}>{errorMsg}</p>
            <button onClick={handleDownload} style={{ padding: '10px 20px', backgroundColor: '#1e40af', color: '#fff', border: 'none', borderRadius: 8, fontSize: 13, fontWeight: 600, cursor: 'pointer', fontFamily: 'inherit' }}>
              Try again
            </button>
          </div>
        )}

        <div style={{ marginTop: 24 }}>
          <Link href={`/dashboard/analysis/${analysis.id}`} style={{ display: 'inline-flex', alignItems: 'center', gap: 6, fontSize: 13, color: '#6b7280', textDecoration: 'none' }}>
            <ArrowLeft size={14} /> Back to analysis
          </Link>
        </div>
      </div>

      <style>{`@keyframes spin { from{transform:rotate(0deg)} to{transform:rotate(360deg)} }`}</style>
    </div>
  )
}