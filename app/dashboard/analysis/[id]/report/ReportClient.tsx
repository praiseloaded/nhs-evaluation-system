// ─── jsPDF wrapper ────────────────────────────────────────────────────────────
type Doc = any

async function loadJsPDF(): Promise<{ jsPDF: any; autoTable: any }> {
  const [{ jsPDF }, autoTable] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
  ])
  return { jsPDF, autoTable: autoTable.default }
}

// ─── Hex to RGB ───────────────────────────────────────────────────────────────
function hex(h: string): [number, number, number] {
  const n = parseInt(h.replace('#',''), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

// ─── Page metrics ─────────────────────────────────────────────────────────────
const PW = 210        // A4 width mm
const PH = 297        // A4 height mm
const ML = 15         // left margin
const MR = 15         // right margin
const CW = PW - ML - MR  // content width
const HEADER_H = 18
const FOOTER_H = 12

// ─── Draw header ─────────────────────────────────────────────────────────────
function drawHeader(doc: Doc, jobTitle: string, createdAt: string) {
  // Navy bar
  doc.setFillColor(...hex(C.navy))
  doc.rect(0, 0, PW, HEADER_H, 'F')

  // Blue accent line
  doc.setFillColor(...hex(C.accblue))
  doc.rect(0, HEADER_H - 1, PW, 1, 'F')

  // Left: branding
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.setTextColor(...hex(C.white))
  doc.text('NHS JobReady AI', ML, 8)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  doc.setTextColor(...hex(C.litblue))
  doc.text('Full Application Analysis Report', ML, 13)

  // Right: job title + date
  const title = jobTitle.length > 52 ? jobTitle.slice(0, 52) + '…' : jobTitle
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(8.5)
  doc.setTextColor(...hex(C.white))
  doc.text(title, PW - MR, 8, { align: 'right' })
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  doc.setTextColor(...hex(C.litblue))
  doc.text(createdAt, PW - MR, 13, { align: 'right' })
}

// ─── Draw footer ─────────────────────────────────────────────────────────────
function drawFooter(doc: Doc, pageNum: number, totalPages: number, createdAt: string) {
  const y = PH - FOOTER_H
  doc.setFillColor(...hex(C.lgray))
  doc.rect(0, y, PW, FOOTER_H, 'F')
  doc.setFillColor(...hex(C.mgray))
  doc.rect(0, y, PW, 0.3, 'F')

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(6.5)
  doc.setTextColor(...hex(C.dgray))
  doc.text('Confidential — for applicant use only. Generated by NHS JobReady AI.', ML, y + 4.5)
  doc.text(createdAt, PW / 2, y + 4.5, { align: 'center' })
  doc.setFont('helvetica', 'bold')
  doc.text(`Page ${pageNum} of ${totalPages}`, PW - MR, y + 4.5, { align: 'right' })
}

// ─── Cursor tracker ───────────────────────────────────────────────────────────
class Cursor {
  y: number
  doc: Doc
  jobTitle: string
  createdAt: string
  pageNum: number

  constructor(doc: Doc, jobTitle: string, createdAt: string) {
    this.doc       = doc
    this.jobTitle  = jobTitle
    this.createdAt = createdAt
    this.y         = HEADER_H + 8
    this.pageNum   = 1
  }

  check(needed: number) {
    if (this.y + needed > PH - FOOTER_H - 4) this.newPage()
  }

  newPage() {
    this.doc.addPage()
    this.pageNum++
    drawHeader(this.doc, this.jobTitle, this.createdAt)
    this.y = HEADER_H + 8
  }

  gap(n = 4) { this.y += n }
}

// ─── Text helpers ─────────────────────────────────────────────────────────────
function sectionHeading(cur: Cursor, title: string) {
  cur.check(14)
  cur.gap(4)
  cur.doc.setFillColor(...hex(C.lblue))
  cur.doc.rect(ML, cur.y, CW, 9, 'F')
  cur.doc.setFont('helvetica', 'bold')
  cur.doc.setFontSize(9)
  cur.doc.setTextColor(...hex(C.blue))
  cur.doc.text(title.toUpperCase(), ML + 4, cur.y + 6)
  cur.y += 12
}

function bodyText(cur: Cursor, text: string, opts?: { color?: string; bold?: boolean; size?: number; indent?: number }) {
  const size   = opts?.size   ?? 8.5
  const color  = opts?.color  ?? C.dgray
  const indent = opts?.indent ?? 0
  cur.doc.setFont('helvetica', opts?.bold ? 'bold' : 'normal')
  cur.doc.setFontSize(size)
  cur.doc.setTextColor(...hex(color))

  const lines = cur.doc.splitTextToSize(text, CW - indent - 2)
  for (const line of lines) {
    cur.check(5)
    cur.doc.text(line, ML + indent, cur.y)
    cur.y += 4.5
  }
}

function scoreBar(cur: Cursor, label: string, value: number) {
  cur.check(10)
  const pct   = Math.max(0, Math.min(100, Math.round(value || 0)))
  const color = pct >= 70 ? C.green : pct >= 50 ? C.amber : C.red
  const barW  = CW - 100 - 12

  cur.doc.setFont('helvetica', 'normal')
  cur.doc.setFontSize(8)
  cur.doc.setTextColor(...hex(C.dgray))
  cur.doc.text(label, ML, cur.y + 3)

  // Track background
  cur.doc.setFillColor(...hex(C.mgray))
  cur.doc.roundedRect(ML + 100, cur.y, barW, 4, 1, 1, 'F')

  // Fill
  if (pct > 0) {
    cur.doc.setFillColor(...hex(color))
    cur.doc.roundedRect(ML + 100, cur.y, barW * pct / 100, 4, 1, 1, 'F')
  }

  // Percentage
  cur.doc.setFont('helvetica', 'bold')
  cur.doc.setFontSize(8)
  cur.doc.setTextColor(...hex(color))
  cur.doc.text(`${pct}%`, ML + 100 + barW + 4, cur.y + 3)

  cur.y += 8
}

function criterionRow(cur: Cursor, c: any) {
  const status = c.status ?? 'not met'
  const bg     = status === 'met' ? C.lgreen : status === 'partially met' ? C.lamber : C.lred
  const fg     = status === 'met' ? C.green  : status === 'partially met' ? C.amber  : C.red
  const icon   = status === 'met' ? '✓' : status === 'partially met' ? '~' : '✗'

  const segs: BoxSegment[] = [
    { text: `${icon}  ${c.criterion || ''}`, size: 8.5, bold: true, color: fg },
  ]
  if (c.evidence)    segs.push({ text: `"${c.evidence}"`,      size: 7.5, italic: true, color: C.dgray, indent: 2 })
  if (c.improvement) segs.push({ text: `→ ${c.improvement}`,  size: 7.5, color: C.amber, indent: 2 })

  boxSegments(cur, segs, bg)
}

function pill(cur: Cursor, text: string, bg: string, fg: string) {
  const w = cur.doc.getStringUnitWidth(text) * 7.5 / cur.doc.internal.scaleFactor + 6
  cur.doc.setFillColor(...hex(bg))
  cur.doc.roundedRect((cur as any)._pillX, cur.y - 3.5, w, 5, 1.5, 1.5, 'F')
  cur.doc.setFont('helvetica', 'normal')
  cur.doc.setFontSize(7.5)
  cur.doc.setTextColor(...hex(fg))
  cur.doc.text(text, (cur as any)._pillX + 3, cur.y)
  return w + 3
}

// Extend Cursor with pill tracking
;(Cursor.prototype as any)._pillX = ML

function pillRow(cur: Cursor, items: Array<{ label: string; bg: string; fg: string }>) {
  cur.check(10)
  ;(cur as any)._pillX = ML
  let rowH = 6
  for (const item of items) {
    const w = cur.doc.getStringUnitWidth(item.label) * 7.5 / cur.doc.internal.scaleFactor + 8
    if ((cur as any)._pillX + w > ML + CW) {
      cur.y += rowH
      ;(cur as any)._pillX = ML
    }
    cur.doc.setFillColor(...hex(item.bg))
    cur.doc.roundedRect((cur as any)._pillX, cur.y - 3.5, w, 5.5, 1.5, 1.5, 'F')
    cur.doc.setFont('helvetica', 'normal')
    cur.doc.setFontSize(7.5)
    cur.doc.setTextColor(...hex(item.fg))
    cur.doc.text(item.label, (cur as any)._pillX + 3, cur.y + 0.5)
    ;(cur as any)._pillX += w + 3
  }
  cur.y += rowH + 2
}

// box() — measures all wrapped lines first, draws background to fit, then writes text
// Each entry in `segments` is { text, size?, bold?, italic?, color?, indent? }
interface BoxSegment { text: string; size?: number; bold?: boolean; italic?: boolean; color?: string; indent?: number }

function boxSegments(cur: Cursor, segments: BoxSegment[], bg: string) {
  const PAD_X = 5
  const PAD_Y = 5
  const LINE_GAP = 1.2

  // Pre-compute all wrapped lines with their styles
  type RendLine = { text: string; size: number; bold: boolean; italic: boolean; color: string; indent: number; leading: number }
  const rendLines: RendLine[] = []

  for (const seg of segments) {
    const size   = seg.size   ?? 8.5
    const bold   = seg.bold   ?? false
    const italic = seg.italic ?? false
    const color  = seg.color  ?? C.dgray
    const indent = seg.indent ?? 0
    const leading = size * 0.45 + LINE_GAP

    cur.doc.setFont('helvetica', italic ? 'oblique' : bold ? 'bold' : 'normal')
    cur.doc.setFontSize(size)
    const maxW = CW - PAD_X * 2 - indent
    const wrapped: string[] = cur.doc.splitTextToSize(seg.text || '', maxW)
    for (const w of wrapped) {
      rendLines.push({ text: w, size, bold, italic, color, indent, leading })
    }
  }

  // Total height
  const totalH = rendLines.reduce((acc, l) => acc + l.leading, 0) + PAD_Y * 2

  // Page break if needed
  cur.check(totalH + 3)

  // Draw background
  cur.doc.setFillColor(...hex(bg))
  cur.doc.roundedRect(ML, cur.y, CW, totalH, 2, 2, 'F')

  // Write lines
  let ty = cur.y + PAD_Y + rendLines[0]?.leading * 0.75
  for (const l of rendLines) {
    cur.doc.setFont('helvetica', l.italic ? 'oblique' : l.bold ? 'bold' : 'normal')
    cur.doc.setFontSize(l.size)
    cur.doc.setTextColor(...hex(l.color))
    cur.doc.text(l.text, ML + PAD_X + l.indent, ty)
    ty += l.leading
  }

  cur.y += totalH + 3
}

// Convenience wrapper for simple single-colour boxes
function box(cur: Cursor, lines: string[][], bg: string, fg: string, bold = false) {
  boxSegments(cur, lines.map(([l]) => ({ text: l || '', bold, color: fg })), bg)
}

// ─── Metric cards ─────────────────────────────────────────────────────────────
function metricCards(cur: Cursor, cards: Array<{ label: string; value: string | number; bg: string; fg: string }>) {
  const cardW = (CW - (cards.length - 1) * 3) / cards.length
  cur.check(22)
  cards.forEach((card, i) => {
    const x = ML + i * (cardW + 3)
    cur.doc.setFillColor(...hex(card.bg))
    cur.doc.roundedRect(x, cur.y, cardW, 18, 2, 2, 'F')
    cur.doc.setFont('helvetica', 'bold')
    cur.doc.setFontSize(18)
    cur.doc.setTextColor(...hex(card.fg))
    cur.doc.text(String(card.value), x + cardW / 2, cur.y + 11, { align: 'center' })
    cur.doc.setFont('helvetica', 'normal')
    cur.doc.setFontSize(7)
    cur.doc.text(card.label, x + cardW / 2, cur.y + 16, { align: 'center' })
  })
  cur.y += 22
}

// ─── Main PDF builder ─────────────────────────────────────────────────────────
async function buildPDF(analysis: any, result: any, jobTitle: string, createdAt: string): Promise<Blob> {
  const { jsPDF } = await loadJsPDF()
  const doc: Doc  = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' })

  const sb  = result.scoredBreakdown ?? {}
  const bd  = result.breakdown ?? {}
  const am  = result.atsMatch ?? {}
  const sc  = result.statementScan ?? {}
  const overall = sb.overallScore ?? 0
  const overallColor = overall >= 70 ? C.green : overall >= 50 ? C.amber : C.red

  // ── Cover page ────────────────────────────────────────────────────────────
  drawHeader(doc, jobTitle, createdAt)
  const cur = new Cursor(doc, jobTitle, createdAt)

  // Large navy cover block
  doc.setFillColor(...hex(C.navy))
  doc.roundedRect(ML, cur.y, CW, 55, 4, 4, 'F')

  // NHS JobReady label
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  doc.setTextColor(...hex(C.litblue))
  doc.text('NHS JOBREADY AI  ·  FULL APPLICATION ANALYSIS REPORT', ML + 6, cur.y + 8)

  // Job title
  const titleLines = doc.splitTextToSize(jobTitle, CW - 120)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.setTextColor(...hex(C.white))
  titleLines.forEach((l: string, i: number) => doc.text(l, ML + 6, cur.y + 17 + i * 8))

  // Meta
  const meta = [analysis.band, analysis.location, `Confidence: ${result.confidence ?? '—'}%`].filter(Boolean).join('  ·  ')
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.setTextColor(...hex(C.litblue))
  doc.text(meta, ML + 6, cur.y + 34)

  // Overall score — right side of cover
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(44)
  doc.setTextColor(...hex(overallColor))
  doc.text(`${overall}%`, PW - MR - 6, cur.y + 28, { align: 'right' })
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.setTextColor(...hex(C.litblue))
  doc.text('OVERALL SCORE', PW - MR - 6, cur.y + 34, { align: 'right' })

  // Sub-scores under cover
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(7.5)
  doc.setTextColor(...hex(C.white))
  const subScores = [
    `Criteria Coverage: ${sb.criteriaCoverage ?? '—'}%`,
    `Values Alignment: ${sb.valuesAlignment ?? '—'}%`,
    `Language Mirroring: ${sb.languageMirroring ?? '—'}%`,
  ]
  subScores.forEach((s, i) => doc.text(s, ML + 6, cur.y + 43 + i * 4))

  cur.y += 62

  // ── Score Breakdown ───────────────────────────────────────────────────────
  sectionHeading(cur, 'Score Breakdown')
  ;[
    ['Overall Score',      sb.overallScore],
    ['Criteria Coverage',  sb.criteriaCoverage],
    ['Values Alignment',   sb.valuesAlignment],
    ['Language Mirroring', sb.languageMirroring],
    ['STAR Completeness',  sb.starCompleteness],
    ['Specificity',        sb.specificity],
  ].forEach(([l, v]) => scoreBar(cur, String(l), Number(v || 0)))

  // Internal metrics
  const int = sb._internal ?? {}
  if (Object.keys(int).length) {
    cur.check(10)
    doc.setFillColor(...hex(C.lgray))
    doc.roundedRect(ML, cur.y, CW, 8, 2, 2, 'F')
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(7)
    doc.setTextColor(...hex('#6b7280'))
    const intText = [
      `Essential ratio: ${Math.round((int.essentialRatio || 0) * 100)}%`,
      `Desirable ratio: ${Math.round((int.desirableRatio || 0) * 100)}%`,
      `Essential ceiling: ${int.essentialCeiling ?? '—'}`,
      `Seniority deduction: -${int.seniorityDeduction ?? 0}pts`,
      `Desirable penalty: -${int.desirablePenalty ?? 0}pts`,
    ].join('   ·   ')
    doc.text(intText, ML + 4, cur.y + 5)
    cur.y += 11
  }

  // ── Statement Analysis ────────────────────────────────────────────────────
  if (sc.wordCount != null) {
    sectionHeading(cur, 'Statement Analysis')
    metricCards(cur, [
      { label: 'Word count',    value: sc.wordCount ?? 0,     bg: C.lblue,  fg: C.blue  },
      { label: 'Examples',      value: sc.exampleCount ?? 0,  bg: sc.hasExamples  ? C.lgreen : C.lred, fg: sc.hasExamples  ? C.green : C.red },
      { label: 'Results shown', value: sc.resultsPresent ? 'Yes' : 'No', bg: sc.resultsPresent ? C.lgreen : C.lred, fg: sc.resultsPresent ? C.green : C.red },
      { label: 'Uses "we"',     value: sc.usesWeLanguage ? 'Yes' : 'No', bg: sc.usesWeLanguage ? C.lred : C.lgreen, fg: sc.usesWeLanguage ? C.red : C.green },
      { label: 'Generic open',  value: sc.openingIsGeneric ? 'Yes' : 'No', bg: sc.openingIsGeneric ? C.lred : C.lgreen, fg: sc.openingIsGeneric ? C.red : C.green },
      { label: 'Generic close', value: sc.closingIsGeneric ? 'Yes' : 'No', bg: sc.closingIsGeneric ? C.lred : C.lgreen, fg: sc.closingIsGeneric ? C.red : C.green },
    ])
  }

  // ── ATS Match ─────────────────────────────────────────────────────────────
  if (am.totalKeywords) {
    sectionHeading(cur, 'ATS Keyword Match')
    metricCards(cur, [
      { label: 'Found',   value: am.foundCount   ?? 0, bg: C.lgreen, fg: C.green },
      { label: 'Missing', value: am.missingCount  ?? 0, bg: C.lred,   fg: C.red   },
      { label: 'Total',   value: am.totalKeywords ?? 0, bg: C.lblue,  fg: C.blue  },
    ])
    if (am.keywordsFound?.length) {
      bodyText(cur, 'Found keywords:', { bold: true, size: 8 })
      cur.gap(1)
      pillRow(cur, am.keywordsFound.map((k: string) => ({ label: k, bg: C.lgreen, fg: C.green })))
    }
    if (am.keywordsMissing?.length) {
      bodyText(cur, 'Missing keywords:', { bold: true, size: 8 })
      cur.gap(1)
      pillRow(cur, am.keywordsMissing.map((k: string) => ({ label: k, bg: C.lred, fg: C.red })))
    }
    cur.gap(4)
  }

  // ── Essential Criteria ────────────────────────────────────────────────────
  const ess = (result.criteriaAnalysis ?? []).filter((c: any) => c.type === 'essential')
  const des = (result.criteriaAnalysis ?? []).filter((c: any) => c.type === 'desirable')
  const essMet = ess.filter((c: any) => c.status === 'met').length
  const desMet = des.filter((c: any) => c.status === 'met').length

  if (ess.length) {
    sectionHeading(cur, `Essential Criteria (${essMet}/${ess.length} met)`)
    ess.forEach((c: any) => criterionRow(cur, c))
    cur.gap(4)
  }

  if (des.length) {
    sectionHeading(cur, `Desirable Criteria (${desMet}/${des.length} met)`)
    des.forEach((c: any) => criterionRow(cur, c))
    cur.gap(4)
  }

  // ── NHS Values ────────────────────────────────────────────────────────────
  const nhsVals = result.nhsValues ?? []
  if (nhsVals.length) {
    sectionHeading(cur, 'NHS Values')
    nhsVals.forEach((v: any) => {
      const absent = v.classification === 'absent'
      const fg = absent ? C.red : C.green
      const bg = absent ? C.lred : C.lgreen
      const segs: BoxSegment[] = [
        { text: `${absent ? '✗' : '✓'}  ${v.name}  [${v.classification}]`, size: 8.5, bold: true, color: fg },
      ]
      if (v.evidence) segs.push({ text: `"${v.evidence}"`, size: 7.5, italic: true, color: C.dgray, indent: 2 })
      boxSegments(cur, segs, bg)
    })
    cur.gap(2)
  }

  // ── Strengths ─────────────────────────────────────────────────────────────
  if (result.strengths?.length) {
    sectionHeading(cur, 'Strengths')
    result.strengths.forEach((s: any) => {
      const claim    = typeof s === 'string' ? s : s.claim ?? ''
      const evidence = typeof s === 'string' ? '' : s.evidence ?? ''
      const segs: BoxSegment[] = [{ text: `✓  ${claim}`, size: 8.5, bold: true, color: C.green }]
      if (evidence) segs.push({ text: `"${evidence}"`, size: 7.5, italic: true, color: C.dgray, indent: 2 })
      boxSegments(cur, segs, C.lgreen)
    })
    cur.gap(2)
  }

  // ── Weaknesses ────────────────────────────────────────────────────────────
  if (result.weaknesses?.length) {
    sectionHeading(cur, 'Weaknesses')
    result.weaknesses.forEach((w: string) => box(cur, [[`✗  ${w}`]], C.lred, C.red))
    cur.gap(2)
  }

  // ── Missing Criteria ──────────────────────────────────────────────────────
  if (result.missingCriteria?.length) {
    sectionHeading(cur, 'Missing Criteria')
    pillRow(cur, result.missingCriteria.map((m: string) => ({ label: `○  ${m}`, bg: C.lamber, fg: C.amber })))
    cur.gap(4)
  }

  // ── Recommendations ───────────────────────────────────────────────────────
  if (result.recommendations?.length) {
    sectionHeading(cur, 'Recommendations')
    result.recommendations.forEach((r: any, i: number) => {
      const gap       = typeof r === 'string' ? '' : r.gap ?? ''
      const directive = typeof r === 'string' ? r : r.directive ?? ''
      const segs: BoxSegment[] = []
      if (gap) segs.push({ text: `${i+1}.  ${gap}`, size: 8.5, bold: true, color: C.blue })
      segs.push({ text: gap ? `→  ${directive}` : `${i+1}.  ${directive}`, size: 8.5, color: C.blue, indent: gap ? 4 : 0 })
      boxSegments(cur, segs, C.lblue)
    })
    cur.gap(2)
  }

  // ── Rejection Risk ────────────────────────────────────────────────────────
  const rr = result.rejectionRisk ?? {}
  if (rr.gates?.length) {
    sectionHeading(cur, `Rejection Risk  ·  Overall: ${(rr.overall ?? '').toUpperCase()}`)
    rr.gates.forEach((g: any) => {
      const lvl = g.riskLevel ?? 'medium'
      const bg  = lvl === 'low' ? C.lgreen : lvl === 'medium' ? C.lamber : C.lred
      const fg  = lvl === 'low' ? C.green  : lvl === 'medium' ? C.amber  : C.red
      const segs: BoxSegment[] = [
        { text: `[${lvl.toUpperCase()}]  ${g.gate}`, size: 8.5, bold: true, color: fg },
        { text: g.reason ?? '', size: 8, color: C.dgray, indent: 2 },
      ]
      if (g.fix && !['N/A','None needed for this gate.'].includes(g.fix)) {
        segs.push({ text: `Fix: ${g.fix}`, size: 8, color: fg, indent: 2 })
      }
      boxSegments(cur, segs, bg)
    })
    cur.gap(2)
  }

  // ── Operational Realism ───────────────────────────────────────────────────
  const op = result.operationalRealism ?? {}
  if (op.dimensions?.length) {
    sectionHeading(cur, `Operational Realism  ·  ${(op.level ?? '').toUpperCase()}`)
    op.dimensions.forEach((d: any) => {
      const cls = d.classification ?? ''
      const bg  = cls === 'demonstrated' ? C.lgreen : cls === 'implied' ? C.lamber : C.lred
      const fg  = cls === 'demonstrated' ? C.green  : cls === 'implied' ? C.amber  : C.red
      const segs: BoxSegment[] = [
        { text: `[${cls.toUpperCase()}]  ${d.name}`, size: 8.5, bold: true, color: fg },
      ]
      if (d.evidence) segs.push({ text: `"${d.evidence}"`, size: 7.5, italic: true, color: C.dgray, indent: 2 })
      if (d.gap)      segs.push({ text: `Gap: ${d.gap}`, size: 8, color: fg, indent: 2 })
      boxSegments(cur, segs, bg)
    })
    cur.gap(2)
  }

  // ── Band Coaching ─────────────────────────────────────────────────────────
  const bc = result.bandCoaching ?? {}
  if (bc.bandLabel) {
    sectionHeading(cur, `Band Coaching  ·  ${bc.bandLabel}${bc.targetBand ? `  ·  Target: Band ${bc.targetBand}` : ''}`)

    if (bc.coreExpectation) {
      boxSegments(cur, [
        { text: 'Core expectation', size: 8, bold: true, color: C.blue },
        { text: bc.coreExpectation, size: 8.5, color: C.blue, indent: 2 },
      ], C.lblue)
    }

    if (bc.mostCriticalBandGap) {
      boxSegments(cur, [
        { text: 'Most critical gap', size: 8, bold: true, color: C.red },
        { text: bc.mostCriticalBandGap, size: 8.5, color: C.red, indent: 2 },
      ], C.lred)
    }

    const sections: Array<[string, string[], string, string]> = [
      ['Candidate Gaps',        bc.candidateGaps       ?? [], C.lred,   C.red   ],
      ['Band-Specific Tips',    bc.bandSpecificTips    ?? [], C.lblue,  C.blue  ],
      ['What Panels Look For',  bc.whatPanelsLookFor   ?? [], C.lgreen, C.green ],
    ]
    sections.forEach(([title, items, bg, fg]) => {
      if (!items.length) return
      items.forEach((item: string) => boxSegments(cur, [
        { text: title, size: 7.5, bold: true, color: fg },
        { text: `•  ${item}`, size: 8.5, color: fg, indent: 2 },
      ], bg))
    })
    cur.gap(2)
  }

  // ── Language Mirroring Detail ─────────────────────────────────────────────
  const lm = bd.languageMirroring ?? {}
  if (lm.present != null) {
    sectionHeading(cur, 'Language Mirroring Detail')
    metricCards(cur, [
      { label: 'Present',     value: lm.present     ?? 0, bg: C.lgreen, fg: C.green },
      { label: 'Paraphrased', value: lm.paraphrased ?? 0, bg: C.lamber, fg: C.amber },
      { label: 'Absent',      value: lm.absent      ?? 0, bg: C.lred,   fg: C.red   },
    ])
    if (lm.phrasesMissing?.length) {
      bodyText(cur, 'Missing phrases:', { bold: true, size: 8 })
      cur.gap(1)
      pillRow(cur, lm.phrasesMissing.map((p: string) => ({ label: p, bg: C.lred, fg: C.red })))
    }
    cur.gap(4)
  }

  // ── Role Match Suggestions ────────────────────────────────────────────────
  if (result.roleMatchSuggestions?.length) {
    sectionHeading(cur, 'Role Match Suggestions')
    result.roleMatchSuggestions.forEach((r: any) => {
      boxSegments(cur, [
        { text: `${r.roleTitle}  ·  ${r.bandRange}`, size: 8.5, bold: true, color: C.dgray },
        { text: r.reason ?? '', size: 8, color: C.dgray, indent: 2 },
      ], C.lgray)
    })
    cur.gap(2)
  }

  // ── Seniority ─────────────────────────────────────────────────────────────
  const sen = result.seniority ?? {}
  if (sen.targetBand != null) {
    sectionHeading(cur, 'Seniority Assessment')
    metricCards(cur, [
      { label: 'Target band',       value: `Band ${sen.targetBand ?? '—'}`,  bg: C.lblue,  fg: C.blue  },
      { label: 'Demonstrated band', value: sen.demonstratedBand ?? '—',      bg: C.lgray,  fg: C.dgray },
      { label: 'Band gap',          value: sen.bandGap ?? 0,                 bg: sen.bandGap < 0 ? C.lred : C.lgreen, fg: sen.bandGap < 0 ? C.red : C.green },
    ])
  }

  // ── Fix footers on all pages ──────────────────────────────────────────────
  const totalPages = doc.internal.getNumberOfPages()
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p)
    drawFooter(doc, p, totalPages, createdAt)
  }

  return doc.output('blob')
}

// ─── Component ────────────────────────────────────────────────────────────────
export function ReportDownloadClient({ analysisId, jobTitle, analysis, result }: Props) {
  const [status,   setStatus]   = useState<'idle' | 'loading' | 'done' | 'error'>('idle')
  const [errorMsg, setErrorMsg] = useState('')

  const createdAt = new Date(analysis.createdAt).toLocaleDateString('en-GB', {
    day: 'numeric', month: 'long', year: 'numeric',
  })

  async function handleDownload() {
    setStatus('loading')
    setErrorMsg('')
    try {
      const blob = await buildPDF(analysis, result, jobTitle, createdAt)
      const url  = URL.createObjectURL(blob)
      const a    = document.createElement('a')
      a.href     = url
      a.download = `NHS-JobReady-${jobTitle.replace(/[^a-zA-Z0-9]/g, '-').slice(0, 40)}-Report.pdf`
      a.click()
      URL.revokeObjectURL(url)
      setStatus('done')
    } catch (err: any) {
      setErrorMsg(err.message ?? 'Download failed')
      setStatus('error')
    }
  }

  return (
    <div style={{ minHeight: '100vh', backgroundColor: '#f9fafb', fontFamily: 'system-ui, sans-serif', display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', padding: '2rem' }}>
      <div style={{ backgroundColor: '#fff', border: '1px solid #e5e7eb', borderRadius: 16, padding: '48px 40px', maxWidth: 480, width: '100%', textAlign: 'center' }}>

        <div style={{ width: 64, height: 64, borderRadius: '50%', backgroundColor: '#dbeafe', display: 'flex', alignItems: 'center', justifyContent: 'center', margin: '0 auto 20px' }}>
          <FileText size={28} color="#1e40af" />
        </div>

        <h1 style={{ fontSize: 20, fontWeight: 800, color: '#111827', marginBottom: 8 }}>Full Analysis Report</h1>
        <p style={{ fontSize: 14, color: '#6b7280', marginBottom: 6, lineHeight: 1.6 }}>{jobTitle}</p>
        <p style={{ fontSize: 12, color: '#9ca3af', marginBottom: 28 }}>
          Professional A4 PDF — criteria assessment, band coaching, rejection risk, recommendations, ATS analysis, and every scored dimension.
        </p>

        {status === 'idle' && (
          <button onClick={handleDownload} style={{ width: '100%', padding: '14px', backgroundColor: '#1e40af', color: '#fff', border: 'none', borderRadius: 10, fontSize: 15, fontWeight: 700, cursor: 'pointer', display: 'inline-flex', alignItems: 'center', justifyContent: 'center', gap: 8, fontFamily: 'inherit' }}>
            <Download size={18} /> Download PDF Report
          </button>
        )}

        {status === 'loading' && (
          <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 12 }}>
            <Loader2 size={36} color="#1e40af" style={{ animation: 'spin 1s linear infinite' }} />
            <p style={{ fontSize: 14, color: '#6b7280' }}>Building your report…</p>
          </div>
        )}

        {status === 'done' && (
          <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 12 }}>
            <CheckCircle2 size={40} color="#15803d" />
            <p style={{ fontSize: 14, color: '#15803d', fontWeight: 600 }}>Downloaded successfully!</p>
            <button onClick={handleDownload} style={{ padding: '10px 20px', backgroundColor: '#f3f4f6', color: '#374151', border: '1px solid #e5e7eb', borderRadius: 8, fontSize: 13, cursor: 'pointer', fontFamily: 'inherit' }}>
              Download again
            </button>
          </div>
        )}

        {status === 'error' && (
          <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 12 }}>
            <p style={{ fontSize: 13, color: '#991b1b', backgroundColor: '#fee2e2', padding: '10px 16px', borderRadius: 8 }}>{errorMsg}</p>
            <button onClick={handleDownload} style={{ padding: '10px 20px', backgroundColor: '#1e40af', color: '#fff', border: 'none', borderRadius: 8, fontSize: 13, fontWeight: 600, cursor: 'pointer', fontFamily: 'inherit' }}>
              Try again
            </button>
          </div>
        )}

        <div style={{ marginTop: 24 }}>
          <Link href={`/dashboard/analysis/${analysisId}`} style={{ display: 'inline-flex', alignItems: 'center', gap: 6, fontSize: 13, color: '#6b7280', textDecoration: 'none' }}>
            <ArrowLeft size={14} /> Back to analysis
          </Link>
        </div>
      </div>

      <style>{`@keyframes spin { from{transform:rotate(0deg)} to{transform:rotate(360deg)} }`}</style>
    </div>
  )
}