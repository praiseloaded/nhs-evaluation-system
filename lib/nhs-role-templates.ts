export function getRoleById(id: string): RoleTemplate | undefined {
  return ROLE_TEMPLATES.find(r => r.id === id)
}

export function getRolesByCategory(): Record<string, RoleTemplate[]> {
  return ROLE_TEMPLATES.reduce((acc, r) => {
    if (!acc[r.category]) acc[r.category] = []
    acc[r.category].push(r)
    return acc
  }, {} as Record<string, RoleTemplate[]>)
}

export function getEvidencePrompt(
  template: RoleTemplate | null,
  competencyId: string,
  competencyDescription: string
): string {
  if (template?.evidencePrompts[competencyId]) {
    return template.evidencePrompts[competencyId]!
  }
  return `Describe a specific example from your experience that demonstrates: ${competencyDescription}. Include what the situation was, what you did, and what the outcome was.`
}